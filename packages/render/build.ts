// Builds the wasm module, the demo page into demo/dist, and the page of
// `endmark view` into crates/endmark-cli/view.
// Run with `bun run build` in packages/render.
//
// demo/dist is not committed. crates/endmark-cli/view is: the `endmark`
// binary embeds it, so that `cargo install endmark` needs neither bun nor
// this script. After changing anything listed in `INPUTS`, run this script
// and commit what it writes. `cargo test` fails until you do.

import { $ } from "bun";
import { cp, mkdir, readdir, rm } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";

const root = resolve(import.meta.dir, "../..");
const dist = join(root, "demo/dist");
const view = join(root, "crates/endmark-cli/view");
const stage = join(root, "target/endmark-view");
const wasm = join(root, "target/wasm32-unknown-unknown/release/endmark_wasm.wasm");

/**
 * What the embedded page is built from: directories, taken whole, and
 * single files. `crates/endmark-cli/tests/view_assets.rs` has the same
 * list and fails when the committed page was built from anything else.
 */
const INPUTS = {
  directories: ["crates/endmark-core/src", "crates/endmark-wasm/src", "packages/render/src", "view"],
  files: ["packages/render/build.ts", "packages/render/bun.lock", "packages/render/package.json"],
};

const TYPES: Record<string, string> = {
  css: "text/css; charset=utf-8",
  js: "text/javascript; charset=utf-8",
  wasm: "application/wasm",
};

async function bundle(entry: string, outdir: string): Promise<void> {
  await rm(outdir, { recursive: true, force: true });
  const result = await Bun.build({
    entrypoints: [entry],
    outdir,
    target: "browser",
    splitting: true,
    minify: true,
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  await cp(wasm, join(outdir, "endmark.wasm"));
}

async function filesUnder(directory: string): Promise<string[]> {
  const found: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true, recursive: true })) {
    if (entry.isFile()) found.push(relative(root, join(entry.parentPath, entry.name)).split(sep).join("/"));
  }
  return found;
}

/**
 * One SHA-256 over every input: for each file in order of its path, the
 * path, a zero byte, the bytes with CRLF read as LF, and a zero byte.
 */
async function inputsDigest(): Promise<string> {
  const paths = [...INPUTS.files];
  for (const directory of INPUTS.directories) paths.push(...(await filesUnder(join(root, directory))));
  paths.sort();
  const hasher = new Bun.CryptoHasher("sha256");
  for (const path of paths) {
    const text = (await Bun.file(join(root, path)).text()).replaceAll("\r\n", "\n");
    hasher.update(path);
    hasher.update("\0");
    hasher.update(text);
    hasher.update("\0");
  }
  return hasher.digest("hex");
}

/**
 * Writes the staged page as the files the binary embeds: `index.html` as
 * it is, because the server puts a token into it, every other file
 * compressed, and `assets.rs`, which lists them.
 */
async function embed(): Promise<number> {
  await rm(view, { recursive: true, force: true });
  await mkdir(view, { recursive: true });
  const names = (await readdir(stage)).sort();
  const rows: string[] = [];
  for (const name of names) {
    const bytes = await Bun.file(join(stage, name)).bytes();
    if (name === "index.html") {
      const html = new TextDecoder().decode(bytes);
      if (html.split("__ENDMARK_TOKEN__").length !== 2) throw new Error("index.html must hold the token placeholder once");
      await Bun.write(join(view, name), bytes);
      continue;
    }
    const type = TYPES[name.split(".").pop() ?? ""];
    if (!type || !/^[A-Za-z0-9._-]+$/.test(name)) throw new Error(`the page has a file this script does not expect: ${name}`);
    // No file name and no time in the header, so the same input gives the same bytes.
    await Bun.write(join(view, `${name}.gz`), Bun.gzipSync(bytes, { level: 9 }));
    rows.push(`    ("/${name}", "${type}", include_bytes!("${name}.gz")),`);
  }
  const lines = [
    "// Generated by packages/render/build.ts. Do not edit: run `bun run build` in packages/render.",
    "//",
    "// The page that `endmark view` serves. Every file but the page itself is stored",
    "// compressed with gzip, and is sent that way.",
    "//",
    `// inputs: sha256:${await inputsDigest()}`,
    "",
    "/// The page. The server replaces `__ENDMARK_TOKEN__` in it.",
    'pub const INDEX: &str = include_str!("index.html");',
    "",
    "/// Request path, content type, and the gzip-compressed bytes.",
    "pub const ASSETS: &[(&str, &str, &[u8])] = &[",
    ...rows,
    "];",
    "",
  ];
  await Bun.write(join(view, "assets.rs"), lines.join("\n"));
  return names.length + 1;
}

await $`cargo build --release -p endmark-wasm --target wasm32-unknown-unknown`.cwd(root);

await bundle(join(root, "demo/index.html"), dist);
const files = [...new Bun.Glob("**/*").scanSync(dist)];
console.log(`Built ${files.length} files into ${dist}`);

await bundle(join(root, "view/index.html"), stage);
console.log(`Built ${await embed()} files into ${view}`);
